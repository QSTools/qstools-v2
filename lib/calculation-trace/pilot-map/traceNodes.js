// Mirra v6.0 - Calculation Trace - Static Node Definitions
// Each node resolves its value live, from the exact output_contract fields
// the real app pages read - see calculationTraceLiveValues.js for how the
// live-value bag passed into resolve() is assembled.
//
// implementation_status values:
//   "live_verified_field"  - direct field confirmed by reading the exact
//                             hook/selector that produces it.
//   "live_traced_via_hook" - the hook wiring is confirmed; the deeper
//                             calculation file itself was not read this
//                             session, so the arithmetic is not
//                             independently re-derived here.

function safe(fn) {
  return (live) => {
    try {
      const value = fn(live);
      return value === undefined ? null : value;
    } catch (error) {
      return null;
    }
  };
}

